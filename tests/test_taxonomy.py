"""The 11 TRACE indicators map to the 5 expert subcategories (wiki and expert wording)."""

import pytest

from trace_rag.taxonomy import broader_subcategory, map_racism_structure

D, A = "Διάκριση", "Αφομοίωση"

CASES = [
    # (category, wiki label, expert label, expected subcategory)
    (D, "Αναφορές στους ‘άλλους’ ως πρόβλημα", "Αναφορές στους/στις Άλλους/ες ως πρόβλημα", "Ο/Η Άλλος/η ως πρόβλημα"),
    (D, "Αναφορές στους παράνομους/νόμιμους ‘άλλους’", "Αναφορές στους/στις παράνομους/ες ή/και νόμιμους/ες Άλλους/ες", "Ο/Η Άλλος/η ως πρόβλημα"),
    (D, "Αναφορές στους ανώνυμους ‘άλλους’", "Αναφορές στους/στις ανώνυμους/ες Άλλους/ες", "Ο/Η απομακρυσμένος/η Άλλος/η"),
    (D, "Αναφορές στους προσωρινούς ‘άλλους’", "Αναφορές στους/στις προσωρινούς/ές Άλλους/ες", "Ο/Η απομακρυσμένος/η Άλλος/η"),
    (D, "Αναφορές στους αδρανείς ‘άλλους’", "Αναφορές στους/στις αδρανείς Άλλους/ες", "Ο/Η παθητικός/η Άλλος/η"),
    (D, "Αναφορές στους ‘άλλους’ ως θύματα", "Αναφορές στους/στις Άλλους/ες ως θύματα", "Ο/Η παθητικός/η Άλλος/η"),
    (D, "Αναφορές στους ‘άλλους’ ως αποδέκτες βοήθειας", "Αναφορές στους /στις Άλλους/ες ως αποδέκτες/τριες βοήθειας", "Ο/Η παθητικός/η Άλλος/η"),
    (A, "Αναφορές στον όρο ‘ένταξη/ενσωμάτωση’ ή/και σε πρακτικές ένταξης/ενσωμάτωσης", "Αναφορές (γενικευτικές) σε πρακτικές ένταξης/ενσωμάτωσης", "Ασθενής αφομοίωση"),
    (A, "Αναφορές σε μετριασμένους τρόπους αντίκρουσης του ρατσισμού", "Αναφορές σε μετριασμένους τρόπους αντίκρουσης του ρατσισμού", "Ασθενής αφομοίωση"),
    (A, "Αναφορές σε πρακτικές εκμάθησης ελληνικών", "Αναφορές σε πρακτικές εκμάθησης ελληνικών", "Ισχυρή αφομοίωση"),
    (A, "Αναφορές στη θετική στάση των μεταναστών/προσφύγων απέναντι σε αφομοιωτικές πρακτικές", "Αναφορές στη θετική στάση των μεταναστών/τριών ή/και προσφύγων/ισσών απέναντι σε αφομοιωτικές πρακτικές", "Ισχυρή αφομοίωση"),
]


@pytest.mark.parametrize("category,wiki,expert,expected", CASES)
def test_both_wordings_map(category, wiki, expert, expected):
    assert broader_subcategory(category, wiki) == expected
    assert broader_subcategory(category, expert) == expected


def test_structure_is_deduplicated_and_unknowns_reported():
    mapped, unmapped = map_racism_structure({
        D: ["Αναφορές στους ανώνυμους ‘άλλους’", "Αναφορές στους προσωρινούς ‘άλλους’", "κάτι άγνωστο"],
    })
    assert mapped == {D: ["Ο/Η απομακρυσμένος/η Άλλος/η"]}
    assert unmapped == [(D, "κάτι άγνωστο")]
